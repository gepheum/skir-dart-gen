// A companion generator that references every declaration emitted by
// skir-dart-gen through its symbol provider. Analyzing and testing the e2e
// package checks that the provider agrees with generateCode.
import { GENERATOR as DART } from "../dist/index.js";

export const GENERATOR = {
  id: "symbols-check",
  configType: DART.configType,
  generateCode(input) {
    const symbols = DART.symbols({
      ...input,
      config: { importUriPrefix: "../../skirout/" },
    });
    const imports = new Set();
    const use = (symbol) => {
      symbol.imports.forEach((i) => imports.add(i));
      return symbol.reference;
    };
    const records = [];
    const methods = [];
    const rebuilds = [];
    let enumCount = 0;
    for (const module of input.modules) {
      for (const location of module.records) {
        const record = use(symbols.record(location));
        records.push(`${record},\n`);
        if (location.record.recordType !== "enum") {
          continue;
        }
        const cases = location.record.fields.map((variant) => {
          const constructor = use(
            symbols.variantConstructor(location, variant),
          );
          const value = variant.type
            ? use(symbols.variantValue(location, variant))
            : "";
          const rebuilt = constructor.replace(
            "{value}",
            value.replace("{value}", "this"),
          );
          return `case ${use(symbols.variant(location, variant))}:\nreturn ${rebuilt};\n`;
        });
        rebuilds.push(
          `extension Rebuild${enumCount++} on ${record} {\n`,
          `/// Rebuilds the variant from its own value, through the symbol provider.\n`,
          `${record} rebuild() {\n`,
          "switch (kind) {\n",
          ...cases,
          "default:\n",
          "return this;\n",
          "}\n",
          "}\n",
          "}\n\n",
        );
      }
      for (const method of module.methods) {
        methods.push(`${use(symbols.method(module, method))},\n`);
      }
    }
    const code = [
      "// Generated by e2e-test/symbols_check.mjs\n\n",
      ...[...imports].sort().map((i) => `${i}\n`),
      "\n",
      "final records = <Type>[\n",
      ...records,
      "];\n\n",
      "final methods = <Object>[\n",
      ...methods,
      "];\n\n",
      ...rebuilds,
    ].join("");
    return { files: [{ path: "symbols_check.dart", code }] };
  },
};
